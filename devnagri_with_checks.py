"""14 No replacement matched word schwa deletion sensitivity check

Match distinct word types, not repeated fixation rows, exactly on akshara count and Unicode
character count. Select pairs without replacement by minimum total assignment distance, requiring
an absolute Zipf frequency difference no greater than 0.20 and a relative rendered width
difference no greater than 10%. Run the same procedure three ways: HarfBuzz shaped Noto widths
in MECO, actual original Kokila image ink widths on the six validated MECO pages, and HarfBuzz shaped widths in the fully independent PAHEC corpus. Each pair contains one word with
no deleted schwa and one with at least one deleted schwa.

For each outcome, first average log duration within each (word pair, reader, deletion status) cell; compare only readers who read both paired word types. Regress the within reader deleted minus not deleted difference on residual frequency, rendered width, and text position
differences. Report reader clustered, lexical pair clustered, and two way clustered uncertainty.
Because the assignment is made at the word type level, lexical-pair and two way uncertainty are the relevant conservative checks; reader only significance is not sufficient.

"""

from scipy.optimize import linear_sum_assignment

FREQUENCY_CALIPER, WIDTH_CALIPER = 0.20, 0.10
MATCHED_RESULTS = {}

def matched_deletion_sensitivity(frame, width_column, position_column, source):
    required = ["akshara", "psyll", "nchar", "zipf", width_column, "subj"]
    matching_frame = frame.dropna(subset=required).copy()
    matching_frame["deleted"] = (matching_frame.delta > 0).astype(int)
    matching_frame["matched_width"] = matching_frame[width_column].astype(float)
    matching_frame["matched_position"] = matching_frame[position_column].astype(float)
    word_types = (matching_frame[matching_frame.gaze.notna() & (matching_frame.gaze > 0)]
        .groupby("w", as_index=False)
        .agg(akshara=("akshara", "first"), spoken=("psyll", "first"),
             nchar=("nchar", "first"), zipf=("zipf", "first"),
             matched_width=("matched_width", "median"), deleted=("deleted", "first")))

    pair_records = []
    for _, stratum in word_types.groupby(["akshara", "nchar"]):
        plain = stratum[stratum.deleted == 0].reset_index(drop=True)
        deleted = stratum[stratum.deleted == 1].reset_index(drop=True)
        if plain.empty or deleted.empty:
            continue
        frequency_gap = np.abs(plain.zipf.to_numpy()[:, None] - deleted.zipf.to_numpy()[None, :])
        plain_width = plain.matched_width.to_numpy()[:, None]
        deleted_width = deleted.matched_width.to_numpy()[None, :]
        relative_width_gap = np.abs(plain_width - deleted_width) / ((plain_width + deleted_width) / 2)
        acceptable = (frequency_gap <= FREQUENCY_CALIPER) & (relative_width_gap <= WIDTH_CALIPER)
        assignment_cost = np.where(acceptable,
            frequency_gap / FREQUENCY_CALIPER + relative_width_gap / WIDTH_CALIPER, 1e6)
        plain_rows, deleted_rows = linear_sum_assignment(assignment_cost)
        for plain_index, deleted_index in zip(plain_rows, deleted_rows):
            if not acceptable[plain_index, deleted_index]:
                continue
            ordinary, shortened = plain.iloc[plain_index], deleted.iloc[deleted_index]
            pair_records.append({
                "pair": len(pair_records), "plain": ordinary.w, "deleted_word": shortened.w,
                "akshara": ordinary.akshara, "nchar": ordinary.nchar,
                "plain_spoken": ordinary.spoken, "deleted_spoken": shortened.spoken,
                "zipf_gap": frequency_gap[plain_index, deleted_index],
                "relative_width_gap": relative_width_gap[plain_index, deleted_index],
            })

    matched_word_pairs = pd.DataFrame(pair_records)
    assert matched_word_pairs.plain.is_unique and matched_word_pairs.deleted_word.is_unique
    print(f"\n{source}: {len(matched_word_pairs):,} one to one lexical pairs; "
          f"median absolute Zipf gap={matched_word_pairs.zipf_gap.median():.4f}; "
          f"median relative rendered width gap="
          f"{100*matched_word_pairs.relative_width_gap.median():.2f}%")
    if source == "MECO Noto proxy":
        columns = ["plain", "plain_spoken", "deleted_word", "deleted_spoken", "akshara", "zipf_gap", "relative_width_gap"]
        print("Example real word pairs (no deletion vs. deletion):")
        print(matched_word_pairs.sort_values(["zipf_gap", "relative_width_gap"])
              [columns].head(6).round(4).to_string(index=False))

    word_to_pair = pd.concat([
        matched_word_pairs[["pair", "plain"]].rename(columns={"plain": "w"}),
        matched_word_pairs[["pair", "deleted_word"]].rename(columns={"deleted_word": "w"}),
    ], ignore_index=True)
    matched_observations = matching_frame.merge(word_to_pair, on="w", how="inner")
    MATCHED_RESULTS[source] = {}

    for outcome in ["ffd", "gaze", "gopast"]:
        usable = matched_observations[matched_observations[outcome].notna() &
                                      (matched_observations[outcome] > 0)].copy()
        usable["log_duration"] = np.log(usable[outcome])
        per_reader_word = (usable.groupby(["pair", "subj", "deleted"], observed=True)
            .agg(log_duration=("log_duration", "mean"), frequency=("zipf", "mean"),
                 width=("matched_width", "mean"), word_position=("matched_position", "mean"))
            .reset_index())
        paired = per_reader_word.pivot(index=["pair", "subj"], columns="deleted")
        differences = pd.DataFrame(index=paired.index)
        for field in ["log_duration", "frequency", "width", "word_position"]:
            differences[field + "_difference"] = paired[(field, 1)] - paired[(field, 0)]
        differences = differences.dropna().reset_index()
        model = smf.ols("log_duration_difference ~ frequency_difference + width_difference "
                        "+ word_position_difference", differences)
        readers = pd.factorize(differences.subj)[0]
        lexical_pairs = pd.factorize(differences.pair)[0]
        MATCHED_RESULTS[source][outcome] = {}
        print(f"  {outcome.upper()}: {len(differences):,} within reader paired contrasts; "
              f"{differences.pair.nunique()} lexical pairs; {differences.subj.nunique()} readers")
        for label, clusters in [
            ("reader only", readers), ("lexical pair", lexical_pairs),
            ("reader and lexical pair", np.column_stack([readers, lexical_pairs])),
        ]:
            result = model.fit(cov_type="cluster", cov_kwds={"groups": clusters})
            coefficient = result.params["Intercept"]
            confidence = result.conf_int().loc["Intercept"]
            MATCHED_RESULTS[source][outcome][label] = {
                "log_difference": coefficient, "percentage": 100*np.expm1(coefficient),
                "pvalue": result.pvalues["Intercept"],
                "low": 100*np.expm1(confidence.iloc[0]),
                "high": 100*np.expm1(confidence.iloc[1]),
            }
            print(f"    {label:24s} deletion contrast={100*np.expm1(coefficient):+.2f}% "
                  f"p={result.pvalues['Intercept']:.4g}; "
                  f"95% CI=[{100*np.expm1(confidence.iloc[0]):+.2f}%, "
                  f"{100*np.expm1(confidence.iloc[1]):+.2f}%]")

matched_deletion_sensitivity(M, "width_em", "wordnum", "MECO Noto proxy")
matched_deletion_sensitivity(exact, "bitmap_px", "wordnum", "MECO original Kokila image")
matched_deletion_sensitivity(P, "width_em", "roi", "Independent PAHEC")

print("\nInterpretation: gaze appears positive under reader only clustering, but the "
      "lexical pair and two way tests are not significant, including under original image "
      "width matching and in an independent corpus; no robust deletion cost claim.")

"""15 Divergence localization, with the algebra made explicit

When delta = akshara - spoken_syllables is fixed at any constant, the two competing predictors differ only by an intercept shift and necessarily produce the same fitted values and
AIC. This includes both delta = 0 and delta = 1 words. Therefore a nonzero model comparison advantage among all delta > 0 words merely localizes the contrast to a subgroup containing multiple deletion counts; it does not independently demonstrate orthographic processing or an interaction with divergence.

The check is repeated with independently measured original Kokila stimulus image ink bounds on
the alignment validated six page subset.

"""

DIVERGENCE_RESULTS = {}

def report_divergence(frame, width, source, label):
    required = ["gaze", "zipf", "wordnum", width, "akshara", "psyll", "lab", "subj"]
    data = frame.dropna(subset=required).copy()
    data = data[data.gaze > 0].copy()
    data["log_gaze"] = np.log(data.gaze)
    controls = f"zipf + wordnum + {width} + C(lab)"
    written = smf.ols("log_gaze ~ " + controls + " + akshara", data).fit()
    spoken = smf.ols("log_gaze ~ " + controls + " + psyll", data).fit()
    difference = written.aic - spoken.aic
    fixed_deletion = data.delta.nunique() == 1
    if fixed_deletion:
        assert np.isclose(difference, 0, atol=1e-6), difference
    DIVERGENCE_RESULTS[(source, label)] = {"n": len(data), "aic_difference": difference,
                                          "fixed_deletion": fixed_deletion}
    status = "identical by algebra" if fixed_deletion else "multiple deletion counts"
    print(f"{source:15s} {label:22s} n={len(data):6,}; "
          f"AIC(akshara)-AIC(spoken)={difference:+8.3f}; {status}")

for source, frame, width in [("Noto proxy", M, "width_em"),
                             ("original image", exact, "bitmap_px")]:
    for label, subset in [("all words", frame),
                          ("agreement: delta=0", frame[frame.delta == 0]),
                          ("divergent: delta>0", frame[frame.delta > 0]),
                          ("fixed: delta=1", frame[frame.delta == 1])]:
        report_divergence(subset, width, source, label)

