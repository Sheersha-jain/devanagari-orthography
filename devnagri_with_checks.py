"""6 Main model comparison

OLS models on log durations, with standard errors clustered by reader. Every comparison controls
Zipf frequency, word position, laboratory, and HarfBuzz shaped rendered word width.
Negative ΔAIC favours the akshara; significance does not imply a large predictive gain.
"""

def prep(d, poscol):
    d = d.dropna(subset=["akshara","psyll","nchar","zipf","width_em"]).copy()
    for c in ["akshara","psyll","nchar","zipf","width_em",poscol]:
        d["c_"+c] = (d[c] - d[c].mean()) / d[c].std()
    d["c_wpos"] = d["c_"+poscol]
    return d

M = prep(m, "wordnum"); P = prep(p, "roi")

def fit(d, dv, rhs, grp="subj", vc="item"):
    d = d[(d[dv].notna()) & (d[dv] > 0)]
    model = smf.ols(f"np.log({dv}) ~ {rhs}", d).fit(
        cov_type="cluster", cov_kwds={"groups": d[grp]}
    )
    return model, len(d)

CTRL = "c_zipf + c_wpos + c_width_em + C(lab)"
GRID = {"base":CTRL, "+ nchar":CTRL+" + c_nchar", "+ akshara":CTRL+" + c_akshara",
        "+ spoken syllables":CTRL+" + c_psyll",
        "+ all three":CTRL+" + c_nchar + c_akshara + c_psyll"}

ADJUSTED_DAIC = {}
for dv, lab in [("ffd","First fixation duration"), ("gaze","Gaze duration"),
                ("gopast","Go past duration")]:
    print(f"{lab}");
    res = {}
    for name, rhs in GRID.items():
        r, n = fit(M, dv, rhs); res[name] = r
        print(f"  {name:20s} AIC={r.aic:10.1f}")
    r = res["+ all three"]
    print("  coefficients (all three):", "  ".join(
        f"{t.replace('c_','')} b={r.params[t]:+.4f} p={r.pvalues[t]:.2g}"
        for t in ["c_nchar","c_akshara","c_psyll"]))
    dA = res["+ akshara"].aic - res["+ spoken syllables"].aic
    ADJUSTED_DAIC[dv] = dA
    raw, n = fit(M, dv, CTRL+" + akshara")
    print(f"  unstandardized akshara: b={raw.params['akshara']:+.6f} per additional akshara "
          f"p={raw.pvalues['akshara']:.3g} n={n:,}")
    print(f"  head to head dAIC = {dA:+.3f}  "
          f"({'Akshara' if dA < 0 else 'Spoken syllable'} wins)\n")

