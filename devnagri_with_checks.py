"""13 Follow up audit: what the proposed extensions can and cannot establish

The proposed follow up script was written against an earlier, width unadjusted version of
this project. Its additional ideas are useful only after several problems are corrected:

- The landing calculation silently clipped out-of-range character indices, then fitted models to the original land column instead of the newly calculated land_ak column. Neither column contains calibrated pixel coordinates; converting one into the other creates no independent eye tracking measurement.
- The proposed matching operated on repeated reader by word fixation rows, freely reused the same match, counted the same contrast in opposite directions, and controlled neither shaped or image measured width nor reader, site, or item dependence.
- Its sklearn nearest neighbor import was absent from its installation cell. The corrected no replacement matcher below instead uses SciPy, already installed by statsmodels.
- Within any fixed schwa-deletion count, akshara = spoken_syllables + constant`. Models with intercepts therefore have identical fitted values: a better fit in a mixed divergent subgroup can arise only from variation in deletion counts, not merely from written/spoken disagreement.

The checks below retain the validated rendering controls and report their limits explicitly.

13a Character index landing, mapped into akshara ordinals

Only words whose released spelling already equals the punctuation stripped analysis spelling, and only valid in range integer landing indices, are mapped. Invalid coordinates are excluded, never clipped. The resulting akshara ordinal is a deterministic recoding of a character index; it is descriptive, not an independent observation of a physical saccade target.

The inferential comparison therefore retains the original character index response and asks whether adding akshara count changes fit after character count, word frequency, word position, laboratory, and rendered width are already included. Both the full Noto proxy data and the
alignment validated original Kokila image subset are reported.
"""

@lru_cache(maxsize=None)
def akshara_character_map(word):
    """Map each Unicode character to its zero based written akshara ordinal."""
    word = str(word)
    mapping, i, ordinal = [], 0, -1
    while i < len(word):
        point = ord(word[i])
        if point in INDEP_V:
            ordinal += 1
            mapping.append(ordinal)
            i += 1
            while i < len(word) and (ord(word[i]) in SIGNS or word[i] == NUKTA):
                mapping.append(ordinal)
                i += 1
        elif point in CONS:
            ordinal += 1
            mapping.append(ordinal)
            i += 1
            while i < len(word) and word[i] == NUKTA:
                mapping.append(ordinal)
                i += 1
            while i < len(word) and word[i] == VIRAMA:
                mapping.append(ordinal)
                i += 1
                if i < len(word) and ord(word[i]) in CONS:
                    mapping.append(ordinal)
                    i += 1
                    while i < len(word) and word[i] == NUKTA:
                        mapping.append(ordinal)
                        i += 1
                else:
                    break
            if i < len(word) and ord(word[i]) in MATRA:
                mapping.append(ordinal)
                i += 1
            while i < len(word) and (ord(word[i]) in SIGNS or ord(word[i]) in MATRA):
                mapping.append(ordinal)
                i += 1
        else:
            if ordinal < 0:
                return None
            mapping.append(ordinal)
            i += 1
    if not mapping or ordinal + 1 != n_aksharas(word):
        return None
    return tuple(mapping)

